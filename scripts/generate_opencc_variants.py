#!/usr/bin/env python3
"""Generate OpenCcCharacters.kt from OpenCC's TSCharacters.txt.

Usage: python3 -I scripts/generate_opencc_variants.py [path/to/TSCharacters.txt]

Without an argument the pinned OpenCC release is downloaded to a temporary directory.
"""

import sys
import tempfile
import urllib.request
from pathlib import Path

OPENCC_TAG = "ver.1.4.2"
SOURCE_URL = f"https://raw.githubusercontent.com/BYVoid/OpenCC/{OPENCC_TAG}/data/dictionary/TSCharacters.txt"
REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "shared/src/commonMain/kotlin/org/mpc/domain/search/OpenCcCharacters.kt"
CHUNK_CHARS = 8000
LINE_CHARS = 60


def load_source(argv: list[str]) -> str:
    if len(argv) > 1:
        return Path(argv[1]).read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "TSCharacters.txt"
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:
            target.write_bytes(response.read())
        return target.read_text(encoding="utf-8")


def parse(text: str) -> tuple[list[tuple[str, str]], int]:
    pairs: dict[str, str] = {}
    skipped = 0
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        key, values = line.split("\t", 1)
        value = values.split(" ")[0]
        if len(key) != 1 or len(value) != 1:
            skipped += 1
            continue
        if ord(key) > 0xFFFF or ord(value) > 0xFFFF:
            skipped += 1
            continue
        if key != value:
            pairs[key] = value
    return sorted(pairs.items()), skipped


def kotlin_literal(chars: str) -> str:
    escaped = chars.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    lines = [escaped[i : i + LINE_CHARS] for i in range(0, len(escaped), LINE_CHARS)]
    return " +\n        ".join(f'"{line}"' for line in lines)


def render(pairs: list[tuple[str, str]]) -> str:
    traditional = "".join(k for k, _ in pairs)
    simplified = "".join(v for _, v in pairs)
    chunks = range(0, len(pairs), CHUNK_CHARS)
    out = [
        "// Generated by scripts/generate_opencc_variants.py from OpenCC "
        f"{OPENCC_TAG} TSCharacters.txt (Apache-2.0, see third_party/licenses/Apache-2.0.txt).",
        "// Do not edit.",
        "package org.mpc.domain.search",
        "",
    ]
    for index, start in enumerate(chunks):
        out.append(f"private const val TRADITIONAL_{index} =\n    {kotlin_literal(traditional[start:start + CHUNK_CHARS])}")
        out.append(f"private const val SIMPLIFIED_{index} =\n    {kotlin_literal(simplified[start:start + CHUNK_CHARS])}")
        out.append("")
    count = len(chunks)
    traditional_parts = " + ".join(f"TRADITIONAL_{i}" for i in range(count))
    simplified_parts = " + ".join(f"SIMPLIFIED_{i}" for i in range(count))
    out += [
        "private val traditionalToSimplified: Map<Char, Char> by lazy {",
        f"    val traditional = {traditional_parts}",
        f"    val simplified = {simplified_parts}",
        "    traditional.indices.associate { traditional[it] to simplified[it] }",
        "}",
        "",
        "internal fun foldTraditionalToSimplified(text: String): String = buildString(text.length) {",
        "    for (char in text) append(traditionalToSimplified[char] ?: char)",
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    pairs, skipped = parse(load_source(sys.argv))
    OUTPUT.write_text(render(pairs), encoding="utf-8")
    print(f"entries={len(pairs)} skipped={skipped} bytes={OUTPUT.stat().st_size}")


if __name__ == "__main__":
    main()
